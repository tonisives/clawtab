// Run on the mobile document assembled from the production renderer and fixture bridge.
(async () => {
  const checks = [];
  const assert = (ok, text) => { if (!ok) throw Error(text); checks.push(text); };
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const click = text => [...document.querySelectorAll("button")].find(button => (button.textContent === text || button.getAttribute("aria-label") === text)).click();
  const bounds = element => element.getBoundingClientRect();
  const visible = element => bounds(element).top >= 0 && bounds(element).bottom <= innerHeight + 1;
  const fixture = window.fixture;
  fixture.records.clear();
  fixture.log = "Earlier output\n".repeat(100) + "Latest output";
  fixture.settings.hover_expand = false;
  const record = fixture.record("instant");
  record.question_id = "question-instant";
  record.request.template = "question";
  fixture.records.set(record.id, record);
  const snapshot = () => ({ ...fixture.snapshot(), remote: true, arrival: record.id });
  window.nfn.collapse(); window.nfn.receive(snapshot());
  document.getElementById("surface").dispatchEvent(new MouseEvent("mouseenter"));
  const surface = document.getElementById("surface"), card = document.querySelector(".card");
  const actions = document.querySelector(".actions"), input = document.querySelector("textarea");
  assert(card && !surface.getAnimations().length && !card.getAnimations().length, "a mobile arrival shows its view immediately without a layout or content entrance animation");
  assert(getComputedStyle(card).opacity === "1" && surface.offsetWidth === innerWidth, "the initial mobile card is opaque and fills the host width");
  const autoYes = document.querySelector(".auto-yes-button");
  const autoStyle = getComputedStyle(autoYes);
  assert(autoStyle.borderRadius === "999px" && autoStyle.borderTopWidth === "1px" && autoYes.offsetHeight >= 44, "Yes all keeps its rounded orange action style and touch target");
  click("Reply");
  assert(!document.querySelector(".reply-row").hidden && document.activeElement === input && document.querySelector(".card") === card, "the first Reply press reveals and focuses the existing field synchronously");
  assert(!surface.getAnimations().length && !card.getAnimations().length, "opening Reply has no delayed reveal or fade");
  input.value = "Please check the newest output"; input.dispatchEvent(new Event("input"));
  input.setSelectionRange(7, 12);
  fixture.heldOps.add("context"); click("Details");
  const reading = document.querySelector(".details-content");
  assert(!document.querySelector(".message-content").hidden && reading && document.querySelector(".actions") === actions, "Details appends below the message while preserving the action buttons");
  reading.scrollIntoView({ block: "end" });
  assert(document.querySelector("textarea") === input && input.value === "Please check the newest output" && input.selectionStart === 7, "switching to Details preserves the reply draft and selection");
  assert(visible(actions) && visible(document.querySelector(".controls")) && visible(document.querySelector(".reply")), "actions, reply, and Hide details stay visible below the log");
  assert(bounds(reading).bottom <= bounds(actions).top && reading.clientHeight > 60 && bounds(surface).height === innerHeight, "the log fills the available top reading area without overflowing the screen");
  assert(!surface.getAnimations().length && !card.getAnimations().length, "Details is visible immediately while context is still loading");
  fixture.heldOps.delete("context"); fixture.deferred.splice(0).forEach(request => request.complete());
  await sleep(40);
  assert(reading.scrollHeight - reading.scrollTop - reading.clientHeight < 2 && reading.scrollTop > 0, "the first context response opens at the bottom of the log");
  assert(document.querySelector(".card") === card && document.querySelector(".actions") === actions && getComputedStyle(card).opacity === "1", "loading logs does not rebuild or fade the card or actions");
  reading.scrollTop = 0; fixture.log += "\nAnother line"; await sleep(1100);
  assert(reading.scrollTop === 0, "new output preserves the reader's position when they scroll upward");
  click("Hide details");
  assert(!document.querySelector(".message-content").hidden && !document.querySelector(".details-content") && document.querySelector(".card") === card, "Hide details restores the same message view immediately");
  assert(document.querySelector("textarea") === input && input.value === "Please check the newest output", "hiding Details retains the composer and draft");
  input.blur();
  document.querySelector('.acknowledge').click();
  const popup = document.querySelector('.acknowledge-menu');
  assert(popup && visible(popup) && bounds(popup).right <= innerWidth, "the session action popup fits the mobile viewport");
  document.querySelector('.acknowledge-overlay').click();
  assert(!record.dismissed_at && document.activeElement === document.querySelector('.acknowledge'), "closing the session popup keeps the message and returns focus to Got it");
  document.querySelector('[aria-label="Notification list"]').click();
  const tabs = [...document.querySelectorAll('.segments [role="tab"]')];
  const selected = tabs.find(tab => tab.getAttribute("aria-selected") === "true");
  const idle = tabs.find(tab => tab.getAttribute("aria-selected") !== "true");
  assert(selected && idle && getComputedStyle(selected).backgroundColor === "rgb(56, 56, 58)" && getComputedStyle(idle).backgroundColor === "rgba(0, 0, 0, 0)", "mobile segments show one selected segment on a shared neutral track");
  assert(tabs.every(tab => getComputedStyle(tab).borderTopWidth === "0px" && tab.offsetHeight >= 36 && tab.offsetWidth > 40), "segments keep regular borderless styling and usable targets");
  window.nfn.receive({ type: "hide" });
  assert(surface.classList.contains("empty"), "a warm inactive popup hides its view instead of reloading its document");
  window.nfn.receive(snapshot()); window.nfn.receive({ type: "open_record", id: record.id, popup: true });
  assert(document.querySelector(".card") && !surface.getAnimations().length, "reactivating the warm popup immediately presents the selected message");
  assert(!fixture.calls.some(command => ["respond", "auto_yes", "todo_update", "todo_start"].includes(command.op)), "presentation checks do not answer prompts or change tasks");
  return { passed: checks.length, checks, viewport: { width: innerWidth, height: innerHeight } };
})()
