(async () => {
  const checks = [];
  const assert = (ok, text) => { if (!ok) throw Error(text); checks.push(text); };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  window.ReactNativeWebView = { postMessage: raw => window.webkit.messageHandlers.nfn.postMessage(JSON.parse(raw)) };
  const fixture = window.fixture;
  window.nfn.collapse(); fixture.records.clear();
  fixture.log = "Selection stays here\nA second line\nA final visible line";
  const record = fixture.record("selection-lifecycle");
  fixture.records.set(record.id, record);
  window.nfn.receive({ ...fixture.snapshot(), remote: true, native_chrome: true });
  window.nfn.receive({ type: "open_record", id: record.id });
  await wait(150);
  window.nfn.receive({ type: "mobile_action", action: "reply" });
  const input = document.querySelector(".shell-keyboard");
  const logs = document.querySelector(".logs");
  assert(input && logs, "cached shell and reply input are mounted");
  const originalHeight = innerHeight;
  Object.defineProperty(window, "innerHeight", { value: 500, configurable: true });
  window.nfnMobile.setInsets(0, true);
  await wait(50);
  logs.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true, clientX: 30, clientY: 100 }));
  await wait(450);
  assert(document.activeElement === input, "long press does not blur the input or dismiss its keyboard mid gesture");
  const range = document.createRange(); range.selectNodeContents(logs);
  const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
  const before = range.getBoundingClientRect();
  assert(before.height > 0 && before.top >= 0 && before.bottom <= 501, "selection is positioned inside the keyboard-sized viewport");
  fixture.log = "An update while selecting";
  await wait(1100);
  assert(logs.textContent.includes("Selection stays here") && selection.anchorNode.isConnected, "live capture cannot replace selected text nodes");
  fixture.log = "Selection stays here\nA second line\nA final visible line";
  window.nfn.receive({ type: "mobile_visibility", active: false });
  assert(selection.isCollapsed, "leaving for details clears the old native range");
  Object.defineProperty(window, "innerHeight", { value: originalHeight, configurable: true });
  window.nfnMobile.setInsets(34, false);
  window.nfn.receive({ type: "mobile_visibility", active: true });
  await wait(150);
  assert(document.querySelector(".logs") === logs, "returning keeps the cached shell mounted");
  assert(window.scrollY === 0, "returning clears the outer document scroll offset");
  const returned = document.createRange(); returned.selectNodeContents(logs);
  selection.addRange(returned);
  const rect = returned.getBoundingClientRect();
  assert(rect.height > 0 && rect.top >= 0 && rect.bottom <= originalHeight + 1, "the same shell can be selected again at its visible coordinates");
  return { passed: checks.length, checks };
})()
