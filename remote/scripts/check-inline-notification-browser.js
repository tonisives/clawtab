// Run against the mobile variant of desktop/tests/nfn-fixture.mjs.
(async () => {
  const checks = [], wait = (ms=150) => new Promise(resolve => setTimeout(resolve, ms));
  const check = (name, pass) => { checks.push({name,pass:Boolean(pass)}); };
  document.documentElement.style.width='414px'; document.body.style.width='414px';
  const action = (action, text) => window.nfn.receive({type:'mobile_action',action,text});
  const tap = element => {
    element.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,clientX:40,clientY:100}));
    element.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:40,clientY:100}));
  };
  const record = fixture.record('inline-shell', 1);
  record.request.template = 'update'; record.request.source.group = 'clawtab'; record.request.body='Ready for review';
  fixture.records.set(record.id, record);
  fixture.log = Array.from({length:100},(_,i)=>'Shell row '+i+' '+ 'content '.repeat(12)).join(String.fromCharCode(10))+'\n'+'x'.repeat(2000);
  const snapshot = {...fixture.snapshot(), remote:true,native_chrome:true,arrival:undefined};
  window.nfn.receive(snapshot); window.nfn.receive({type:'show'}); await wait();
  check('notifications open pending list', Boolean(document.querySelector('.queue')));
  window.nfn.receive({type:'open_record',id:record.id}); await wait(1300);
  const shell = document.querySelector('.logs'), content = document.querySelector('.details-content');
  check('tall notification loads shell by default', Boolean(shell?.textContent.includes('Shell row')));
  const style=getComputedStyle(shell);
  check('shell is readable on black with wrapped text', style.fontSize==='12px' && style.backgroundColor==='rgb(0, 0, 0)' && style.whiteSpace==='pre-wrap');
  check('shell has no horizontal scrolling at iPhone width', content.scrollWidth<=content.clientWidth && shell.scrollWidth<=shell.clientWidth && document.body.scrollWidth<=414);
  check('recent output heading is absent', !document.querySelector('.log-output .block-label'));
  const selection=window.getSelection(),range=document.createRange(),textNode=document.createTreeWalker(shell,NodeFilter.SHOW_TEXT).nextNode(); range.setStart(textNode,0); range.setEnd(textNode,Math.min(5,textNode.length)); selection.removeAllRanges(); selection.addRange(range);
  const selected=selection.toString(); fixture.log+='\nLive output'; await wait(1200);
  tap(shell);
  check('selection survives live output without entering reply', selection.toString()===selected && !document.querySelector('#surface').classList.contains('shell-reply'));
  selection.removeAllRanges();
  shell.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,clientX:40,clientY:100})); await wait(400);
  shell.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:40,clientY:100}));
  check('long press does not enter reply', !document.querySelector('#surface').classList.contains('shell-reply'));
  shell.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,clientX:40,clientY:100}));
  shell.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:40,clientY:180}));
  check('scroll gestures do not enter reply', !document.querySelector('#surface').classList.contains('shell-reply'));
  const original = shell;
  const start=performance.now();
  tap(shell);
  check('reply expands immediately without replacing shell', document.querySelector('#surface').classList.contains('shell-reply') && document.querySelector('.logs')===original && performance.now()-start<100);
  await wait(60);
  check('reply starts at bottom of existing output', content.scrollHeight-content.scrollTop-content.clientHeight<2);
  document.documentElement.style.setProperty('--message-height','420px'); window.dispatchEvent(new Event('message_layout'));
  check('keyboard resizing keeps the newest output visible', content.scrollHeight-content.scrollTop-content.clientHeight<2);
  content.scrollTop=0; content.dispatchEvent(new Event('scroll')); window.dispatchEvent(new Event('message_layout'));
  check('reading older output keeps its scroll position', content.scrollTop===0);
  check('reply focuses inline input', document.activeElement?.classList.contains('shell-keyboard'));
  record.request.title = "Updated while replying";
  window.nfn.receive({...fixture.snapshot(), remote:true, native_chrome:true, arrival:undefined});
  check('live message metadata preserves the shell and input', document.querySelector('.logs')===original && document.activeElement?.classList.contains('shell-keyboard'));
  const input=document.activeElement; input.value='hello'; input.dispatchEvent(new Event('input',{bubbles:true})); await wait();
  check('typing sends direct shell input', fixture.calls.some(command=>command.op==='shell_input' && command.text==='hello'));
  action('shell_input','\x1b[A'); await wait();
  check('arrow sends terminal sequence', fixture.calls.some(command=>command.op==='shell_input' && command.text==='\x1b[A'));
  check('reply keeps cached output without opening a terminal', document.querySelector('.logs')===original && !fixture.calls.some(command=>['shell_reply','pty_attach'].includes(command.op)));
  fixture.heldOps.add('shell_input');
  action('shell_input','\x1b[A'); await wait();
  fixture.deferred.find(item=>item.command.op==='shell_input').complete('Shell input unavailable'); await wait();
  fixture.heldOps.delete('shell_input');
  const notice=document.querySelector('.notice');
  check('reply shows shell input errors', notice?.textContent==='Shell input unavailable' && getComputedStyle(notice).display!=='none');
  action('reply_close');
  check('close retains shell and restores message', !document.querySelector('#surface').classList.contains('shell-reply') && document.querySelector('.logs')===original);
  content.scrollTop=0; action('reply'); await wait(60);
  check('reply button also returns to newest output', content.scrollHeight-content.scrollTop-content.clientHeight<2);
  action('reply_close');
  window.nfn.receive({type:'mobile_action',action:'list'});
  check('center navigation action opens list', Boolean(document.querySelector('.queue')));
  window.nfn.receive({type:'mobile_action',action:'tasks'}); await wait();
  check('task add form starts closed', document.querySelector('.todo-add')?.hidden);
  check('task maintenance controls are absent', !document.querySelector('.todo-refresh') && !document.querySelector('.todo-options'));
  document.querySelector('.todo-add-toggle').click();
  check('plus reveals task form', !document.querySelector('.todo-add')?.hidden);
  const fast=fixture.record('fast-reply',1); fast.request.template='update'; fixture.records.set(fast.id,fast);
  fixture.heldOps.add('context');
  window.nfn.receive({type:'open_record',id:fast.id}); await wait(100); action('reply');
  fixture.deferred.find(item=>item.command.op==='context' && item.command.id===fast.id).complete();
  fixture.heldOps.delete('context'); await wait();
  const fastContent=document.querySelector('.details-content');
  check('reply before first capture also opens at the bottom', fastContent.scrollHeight-fastContent.scrollTop-fastContent.clientHeight<2);
  return checks;
})()
